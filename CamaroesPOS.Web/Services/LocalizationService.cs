    public IReadOnlyCollection<string> AllFrenchKeys => Fr.Keys;
    public IReadOnlyCollection<string> AllEnglishKeys => En.Keys;

    public string T(string key)
    {
        var dict = CurrentLang == "en" ? En : Fr;
        return dict.TryGetValue(key, out var val) ? val : key;
    }

    public void Toggle()
    {
        CurrentLang = CurrentLang == "fr" ? "en" : "fr";
        OnChange?.Invoke();
    }
